"""Generate the panel-mipi-dbi init file for the Waveshare 1.44" LCD HAT (ST7735S).

    python3 mkpanel.py [MADCTL] > /lib/firmware/waveshare144.bin

The kernel's panel-mipi-dbi driver replays these commands when the display is
probed (see config/boot-config.txt). MADCTL (0x36) sets orientation and colour
order: 0x68 = rotated 90 degrees, BGR (matches the HAT held with the joystick on
the left), 0x08 = not rotated. Changing the rotation also swaps the x/y offsets
in config/boot-config.txt.
File format: https://github.com/notro/panel-mipi-dbi/wiki
"""
import sys
MADCTL = int(sys.argv[1], 0) if len(sys.argv) > 1 else 0x68
seq = [
    (0x01, []), ('delay', 150),
    (0x11, []), ('delay', 120),
    (0xB1, [0x01, 0x2C, 0x2D]),
    (0xB2, [0x01, 0x2C, 0x2D]),
    (0xB3, [0x01, 0x2C, 0x2D, 0x01, 0x2C, 0x2D]),
    (0xB4, [0x07]),
    (0xC0, [0xA2, 0x02, 0x84]),
    (0xC1, [0xC5]),
    (0xC2, [0x0A, 0x00]),
    (0xC3, [0x8A, 0x2A]),
    (0xC4, [0x8A, 0xEE]),
    (0xC5, [0x0E]),
    (0xE0, [0x0F, 0x1A, 0x0F, 0x18, 0x2F, 0x28, 0x20, 0x22, 0x1F, 0x1B, 0x23, 0x37, 0x00, 0x07, 0x02, 0x10]),
    (0xE1, [0x0F, 0x1B, 0x0F, 0x17, 0x33, 0x2C, 0x29, 0x2E, 0x30, 0x30, 0x39, 0x3F, 0x00, 0x07, 0x03, 0x10]),
    (0xF0, [0x01]),
    (0xF6, [0x00]),
    (0x3A, [0x05]),
    (0x36, [MADCTL]),
    (0x29, []), ('delay', 20),
]
out = bytearray(b"MIPI DBI" + bytes(7) + bytes([1]))
for cmd, arg in seq:
    if cmd == 'delay':
        out += bytes([0x00, 1, arg])
    else:
        out += bytes([cmd, len(arg)] + arg)
sys.stdout.buffer.write(out)
